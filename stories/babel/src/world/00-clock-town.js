/* 00-clock-town.js —— 游戏内时钟 ＋ 城镇生产/远征（`books#206`；`#172` 批 2 第二笔）
 *
 * 本档回答的问题：「**游戏内时间**怎么记、**城镇设施**何时产出、**远征**怎么批量推进？」
 *
 * 口径（出处：`#206` 票面 ＋ 操作者裁，落档评论 `6008797337`／接口草案 `6008441941`）：
 *   · 时间单位＝**分钟** —— 既有 `babelRun.时间` 本来就是这么用的（温泉 `温泉耗时.分钟 = 60`、
 *     休整／照护按 `cfg.restMinutes`／`careMinutes`）⇒ ★**不换单位、不迁移旧档**：
 *     日／月是**纯派生**（`第几日`／`月`／`日内`），✗ 不另存 ⇒ 旧档里那个分钟数自然继续有效。
 *   · 「分钟 → 日」的换算**只此一处**（`分钟每日`）；零头**累积**（裁㈡）⇒ 既不丢、也不向上取整。
 *   · 日历：**每月 30 日**；备战下限＝**至少 90 日**（裁㈠ ⇒ `>=` 而非 `<=`）。
 *   · 批量推进**单次 ≤ 30 日**；`推进` 是**唯一结算器** —— 内部**逐日**走「单日规则」，
 *     ✗ 不另写一条批量规则（那正是「一个量两个实现」的坑，本仓已记：`ui/battle.js:45`）。
 *   · 「一个量只留一个名字」的四条落法（判据各设一格，见 `verify.mjs` 第 63 组）：
 *     ①「时间」＝`babelRun.时间` 一处 ②「月／日」＝派生函式 ③「生产周期」＝**绝对日号**一处
 *     ④「分钟→日」换算＝`分钟每日` 一处。
 *
 * ⚠ 读路径**不写档**（引擎成文判据「被拒 ⇒ 存档面零变化」，见 `src/core/10-item.js:45-58` 的实测记录）
 *   ⇒ 下列 `…读()` 一律**不建键**；只有 `推进`／`建设施` 在**明确的时间推进或明确指令**上写。
 * ⚠ 装载序：本档早于 `00-l10-city.js`（字典序）⇒ ✗ 不能借用它的 `alive`；本档只判「未死」，
 *   那层「终局」归 L10 管（口径不同，✗ 不混成一个函式）。
 */
const R = setup.RPG, D = setup.DND3;
const BS = (setup.BABEL ??= {});

/* ── 常量：四个名字、四个量（✗ 共用一个「30」）────────────────────────── */
/** ★**唯一**换算常量：「分钟 → 日」只此一处（裁㈡的零头累积由分钟账本身承担）。 */
const 分钟每日 = 1440;
/** 日历：每月日数（票面「月 30 天」）。 */
const 每月日数 = 30;
/** 批量推进上限（票面「批量单次 ≤ 30 日」）。与 `每月日数` **同名不同量** ⇒ 各自留名。 */
const 批量上限日 = 30;
/** 备战下限（裁㈠：**至少** 90 日 ⇒ 判据 `>=`）。 */
const 备战下限日 = 90;
/** 历法起点：第 1 日（分钟账 0 即第 1 日）。 */
const 首日 = 1;

/* ── 时间账：唯一存量 ＋ 纯派生 ──────────────────────────────────────── */
const 运行 = () => (State.variables.babelRun ??= {});
/** 分钟账（**唯一**时间存量）。✗ 不建键、✗ 不改档。 */
const 分钟账 = () => Number(State.variables.babelRun?.时间 ?? 0);
/** 记分钟（既有的分钟级入口；`babel.js` 的温泉与 `00-l10-city.js` 的休整/照护都经此一处）。 */
const 记时间 = (分钟) => {
	const r = 运行();
	r.时间 = Number(r.时间 ?? 0) + Number(分钟 ?? 0);
	return r.时间;
};
/** **已过日数**（派生：分钟账 ÷ 分钟每日 取整）—— 「过了几个**完整**游戏日」。
 *  ⚠ 与 `第几日` **是两个量**（✗ 不同名混用）：`已过日数` 是「走过多少天」（裁㈠「至少 90 日」
 *    用的是这一个 ⇒ 过完 90 整天），`第几日` 是「今天第几天」（含头计数，第 1 日＝第一天）。 */
const 已过日数 = () => Math.floor(分钟账() / 分钟每日);
/** 第几日（派生：**含头计数** ⇒ `已过日数 + 1`）。 */
const 第几日 = () => 已过日数() + 首日;
/** 月（派生）。 */
const 月 = () => Math.floor((第几日() - 1) / 每月日数) + 1;
/** 月内第几日（派生）。 */
const 日内 = () => ((第几日() - 1) % 每月日数) + 1;
/** 历面读数（判据按它取「时钟走格」的读数；✗ 不存）。 */
const 历面 = () => ({ 分钟: 分钟账(), 已过日数: 已过日数(), 第几日: 第几日(), 月: 月(), 日内: 日内() });
/** 备战是否已足（裁㈠：**至少** 90 日 ⇒ 按**已过整日**判，✗ 不按含头计数的 `第几日` —— 否则
 *  会把「还在第 90 日的头一分钟」也算成「备足了 90 日」，比「三月备战」短一天）。 */
const 备战已足 = () => 已过日数() >= 备战下限日;

/* ── 城镇与生产 ─────────────────────────────────────────────────────── */
/** 城镇域**只读**视图（✗ 不建键 ⇒ 读路径零副作用）。 */
const 城读 = () => State.variables.babelTown ?? { 设施: {} };
/** 城镇域**写**入口（只在明确指令/推进里用）—— ★**补号**只在这里做（读路径保持零写 ✓）。 */
const 城写 = () => {
	const t = (State.variables.babelTown ??= { 设施: {} });
	t.设施 ??= {};
	补号();                                  // ★`books#208`：旧档里无号的设施在此补号（**幂等** ✓）
	return t;
};
/** 设施表**只读**（判据按它取读数）。 */
const 设施表 = () => (城读().设施 ?? {});
/** 补号（★`books#208`）：给**无 `entityId`** 的设施补号，并让高水位越过已见号（**幂等** ✓）。
 *  ⚠ 只在**写路径**（`城写`）上调用：读路径必须零写（`10-item.js:45-58` 的既有判据）✓。
 *  ⚠ 为何不能挂在 `save:ready` 上：**引擎零发射**该事件（唯一发射＝verify 工具侧的**合成**）⇒ 生产里不跑 ✓。 */
const 补号 = () => {
	for (const f of Object.values(State.variables.babelTown?.设施 ?? {})) {
		if (!f) continue;
		if (!f.entityId) f.entityId = R.newEntityId(); else R.noteEntityId(f.entityId);
	}
};

/** 某设施的默认形：`下次产出日` 存**绝对日号**（✗ 不存「还差几天」——相对量会随推进腐坏）。 */
const 设施形 = (id, { 周期 = 30, 等级 = 1, 产出 = id } = {}) => ({
	id, 等级, 周期, 产出,
	/* ★`books#208`：设施也是**实体**（building 域）⇒ 出生即带号（同 `Item` 的口径）。
	 *   发号器**全局单调** ✓，且经此进档的号会把高水位顶上去（`newEntityId` 自己顶 ✓） */
	entityId: R.newEntityId(),
	开工日: 第几日(),
	下次产出日: 第几日() + 周期,
	库存: 0,
});
/** 建（或取）一座设施 —— **明确指令**才调用（✗ 不在读路径）。 */
const 建设施 = (id, 选项) => {
	const t = 城写();
	t.设施 ??= {};
	return (t.设施[id] ??= 设施形(id, 选项));
};
/** 单日生产结算：到期的设施**逐周期**发放一次（✗ 同一天不重复发同一期）。 */
const 结算日 = (今日) => {
	const 出 = [];
	for (const [id, f] of Object.entries(设施表())) {
		let 次 = Number(f.下次产出日 ?? 0);
		while (次 > 0 && 次 <= 今日) {
			f.库存 = Number(f.库存 ?? 0) + 1;
			出.push({ 设施: id, 日: 次 });
			次 += Number(f.周期 ?? 0) || 1;
		}
		if (次 > 0) f.下次产出日 = 次;
	}
	return 出;
};

/* ── 远征 ───────────────────────────────────────────────────────────── */
/** 在途远征（无 ⇒ `null`）。★「在途」只由**有无这个键**表示（一个量一个名字）。 */
const 远征读 = () => State.variables.babelRun?.远征 ?? null;
/** 出发：记 `出发日`／`预计归日`（绝对日号）⇒ 归期由 `推进` 逐日判定。 */
const 出发 = (日数) => {
	const n = Math.floor(Number(日数));
	if (!Number.isFinite(n) || n < 1 || n > 批量上限日) return { applied: false, 因: `远征日数须为 1..${批量上限日}` };
	if (远征读()) return { applied: false, 因: '已有在途远征' };
	运行().远征 = { 出发日: 第几日(), 预计归日: 第几日() + n };
	return { applied: true, ...远征读() };
};

/* ── 唯一结算器 ─────────────────────────────────────────────────────── */
/** 未死（本档只判这一层；「终局」那层归 L10）。 */
const 未死 = () => D.Player?.hp > 0 && !(D.Player?.contains?.('death'));
/**
 * `推进(日数)` —— **唯一**的时间推进与结算入口。
 * 规则（逐日走，✗ 不写批量特例）：
 *   ①`日数` 非 1..`批量上限日` ⇒ **拒绝**（`applied:false`）且**存档面零变化**
 *   ②逐日：未死才走 → 分钟账 `+分钟每日` → 当日生产结算 → 远征归期判定
 *   ③**中途死亡即停**：停在当日、余量**不结算**（与 `#172` 批 1「批量中途死亡即停」同族）
 */
const 推进 = (日数) => {
	const n = Math.floor(Number(日数));
	if (!Number.isFinite(n) || n < 1 || n > 批量上限日) {
		return { applied: false, 因: `单次推进须为 1..${批量上限日} 日（收到 ${日数}）`, 走了: 0 };
	}
	const r = 运行(), 起 = 第几日();
	let 走了 = 0; const 产出 = []; let 死 = null, 归 = null;
	for (let i = 0; i < n; i++) {
		if (!未死()) { 死 = 第几日(); break; }            // ★③：死则停在当日（该日不推进）
		r.时间 = Number(r.时间 ?? 0) + 分钟每日;            // ★时间推进＝结算的一部分（唯一账）
		走了 += 1;
		const 今日 = 第几日();
		产出.push(...结算日(今日));
		const 在途 = 远征读();
		if (在途 && Number(在途.预计归日 ?? 0) <= 今日) { 归 = { ...在途, 归日: 今日 }; delete State.variables.babelRun.远征; }
	}
	return {
		applied: 走了 > 0, 走了, 起, 止: 第几日(), 历面: 历面(),
		产出, 归, 死: 死, ...(死 ? { 停于: 死, 余量不结算: n - 走了 } : {}),
	};
};

/* ── 挂出机器件 ＋ 旧档补域 ─────────────────────────────────────────── */
/* ★判据/刀要能**真调用**（✗ 只能静态核）⇒ 按本仓成文形挂到 `setup.BABEL`（同 `#177`/`#207` 的理由）。 */
BS.时钟 = { 分钟每日, 每月日数, 批量上限日, 备战下限日, 首日, 分钟账, 记时间, 已过日数, 第几日, 月, 日内, 历面, 备战已足, 推进, 未死 };
BS.城镇 = { 设施表, 建设施, 结算日, 设施形, 出发, 远征读, 城读, 城写, 补号 };   // ★`books#208`：加 城写／补号（判据按**真写口**断旧档补号 ✓）
/** 旧档补域：缺 `babelTown` 才补零（✗ 不追算旧贡献，同 `#350` 的 `ensure` 口径）。
 *  ★`books#208` 备注（改准，dev-9 发现）：**引擎零发射 `save:ready`** —— 唯一发射＝verify 工具侧的**合成**
 *  ⇒ 生产里本监听**不跑** ⇒ 补域/补号**不能**依赖它；真正生效的是**惰性建域**（本档 `城写()`／
 *  `00-l10-city.js` 的 `state()`）与**写路径补号**（本档 `城写()` 里的 `补号()`）✓。
 *  本函数**保留**（verify 工具与将来的宿主若真发射，行为正确 ✓；✗ 删它会留下另一处「假定发射」）✓。 */
const ensure = () => {
	const t = 城写();
	t.设施 ??= {};
};
R.events.on('save:ready', ensure);
