/* books#178／#314：付费回城卷轴。#259 已批准卷轴例外；塔下行步行边不恢复。
 * 传送与 L9 前进步行同落 L10-camp；不复制事件／资源，不复活真死者。
 * 购买复用 L10 候选目录和 RPG.exchange，不另写一套扣钱发货逻辑。
 */
const DND3 = setup.DND3, R = setup.RPG, B = setup.BABEL;
const 聚落 = 'L10-camp', 卷轴 = 'return-scroll';
B.聚落 = 聚落;
B.回城卷轴 = 卷轴;
B.商铺价 = B.L10.cfg.buy;
B.手上有 = (id) => R.heldTotal(DND3.Player, id) ?? 0;
B.买 = (id) => B.L10.buy(id);

DND3.ReturnScroll = R.defItem({
	id: 卷轴, name: '回城卷轴',
	desc: '撕开后回到第 10 层共炉。付费返程不会恢复已经取走的资源或重发事件奖励。',
	charges: 1,
	used() {
		if (!B.L10.alive() || B.战中) {
			this.perform('终局、死亡或战斗中不能用这张返程卷轴。');
			return false;
		}
		if (B.map?.current === 聚落) {
			this.perform('你已经在聚落的共炉边了；这张卷轴留着走远了再用。');
			return false;
		}
		if (!B.map?.locations.has(聚落)) return false;
		/* ★返程接缝（`books#397` 片 3a）：旧卷轴**沿用已冻结的例外**（领队裁 ＋ `writer-2` 四裁 `6018346663`：
		 *   「第3项**不批准**『付费旧卷轴也执行脆弱结算』」✓）⇒ 以 `损毁:false` 走**同一实现** ✓，
		 *   使「豁免」**显式可审** ✗ 不靠「这里没写」✓。★零写、零行为变更 ✓（返回值亦无用 ✓）。 */
		B.返程结算?.旧卷轴返程?.();   // ★具名口（#443 N2 ✓）：冻结例外显式化，✗ 静默豁免 ✓
		B.map.moveTo(聚落);
		this.perform('卷轴烧成灰。再睁眼，是共炉的灯火。次数只由引擎扣除。');
	},
});
// 保留旧营火购买入口和稳定 ID；正式补给目录在配给屋，卷轴两处均证前可买。
B.map.locations.get(聚落).actions.push(B.只给活人({
	text: () => `在共炉边换一张回城卷轴（${B.商铺价[卷轴]} 枚旧硬币；候选）`,
	when: () => !B.战中, action: () => B.买(卷轴),
}));

/* ── W09「七名河」接线（`books#397` · S3 片 1；领队裁 **(b)** `6015911410`）──────────────
 * 本档是 `src/world/**` 里**最后装载**的一档（产品 js 序：… `boss.js` → `babel2.js` → `teleport.js` ✓）
 *   ⇒ 此刻 `B.map`（`babel.js` 建的**唯一**一张图 ✓）与二段的 10→11 门（`babel2.js:141` ✓）都已在位 ✓。
 * 裁 (b) 四条：①教程＝**独立区域 `W09`**（✗ 不占层号 `L11`；`floor 11` 只是**设计口径** ✓）
 *   ②旧 L11 **不顺延**、其地点与边**均不改** —— 本档只把它的**闸门外包一层** ✓（✗ 不重建那条边 ✓）
 *   ③**首次分流互斥**：教程**未完成** ⇒ 出城走 `W09` ✓；**已完成** ⇒ 走旧 L11 ✓（同一条闸门的两面 ✓）
 *   ④**E9 只回 L10**（✗ 不开放下一层 ✓）。
 * ⚠ 本档只做**接线与呈现**：一切状态读写经 `BS.七名河`（`00-seven-names.js` ✓）——✗ 本档不碰存档面 ✓。
 */
{
	const 七 = B.七名河;
	const 地图 = B.map;
	if (七 && 地图) {
		/** ★**分流判据**（唯一出口）：教程未完成 ⇒ 出城走七名河 ✓。判据只读 `读()`（零写 ✓）。 */
		const 应分流 = () => 七.读().态 !== '完成';
		/** 当前节点（含 null 兜底 —— 读面在**未开始**时也有 `当前` ✓）。 */
		const 现节点 = () => 七.读().节点;
		/** 本节点此刻**可选行动**（未处理的事件才有 ✓）。 */
		const 可选项 = () => {
			const r = 七.读(), n = r.节点;
			if (!n || n.type === 'portal' || r.已处理.includes(r.当前)) return [];
			return n.options ?? [];
		};
		/** 本节点此刻**可走方向**（★静态边表是权威 ✓ —— 取 `节点导航`（门向已补 ✓））。 */
		const 可方向 = () => 七.读().导航 ?? [];

		/* ① 教程地点（**独立区域**：id `W09` ✓ 与 `L` 系层号不混 ✓；desc/actions 皆**函数** ⇒ 随状态现算 ✓） */
		const 河岸 = new R.Location({
			id: 'W09',
			name: 'W09 · 七名河（首次出城教程）',
			desc: () => {
				const r = 七.读(), n = r.节点;
				if (!r.已开始) return '浅色的绳、旧渡口、两条向上的路。渡工把一张路图递到你手里 —— 从这里开始，是你的第一次出城。';
				if (!n) return '七名河的雾还没散。';
				const 头 = `${n.title}（${n.type === 'portal' ? '传送门' : n.type === 'battle' ? '战斗' : '奖励'}）`;
				const 线 = n.type === 'portal' ? '你已走过这片河岸。' : (r.已处理.includes(r.当前) ? `★已处理：${r.结果[r.当前]?.成败 ?? ''} —— ${r.结果[r.当前]?.文本 ?? ''}` : '');
				return [头, ...(n.intro ?? []), 线].filter(Boolean).join('\n');
			},
			actions: [
				/* 入场（未开始）⇒ 开始教程（★E0 入场**不消费**机会 ✓ 裁②） */
				B.只给活人({
					text: () => '走进七名河（开始本次教程）',
					when: () => !七.读().已开始, action: () => 七.开始(),
				}),
				/* 三个选项槽（★text 亦为函数 ⇒ 随节点变 ✓；when 现算 ⇒ 已处理即收起 ✓） */
				...[0, 1, 2].map((i) => B.只给活人({
					text: () => 可选项()[i]?.label ?? '',
					when: () => !!可选项()[i], action: () => 七.选行动(i),
				})),
				/* 两个方向槽（左／右＝内容档的 direction ✓） */
				...[0, 1].map((j) => B.只给活人({
					text: () => 可方向()[j]?.label ?? '',
					when: () => !!可方向()[j], action: () => 七.走(可方向()[j].direction),
				})),
			],
		});
		地图.addLocation(河岸);

		/* ② 进场边（**首次分流**）：L10-gate → W09 —— 闸门＝「出城边可通行 ∧ 教程未完成」✓ */
		地图.addExit(new R.Exit({
			from: 'L10-gate', to: 'W09',
			text: '穿过单向门，走进七名河（首次出城教程）',
			when: () => B.边可否通行('L10-gate', 'L11')() && 应分流(),
			action: () => 七.开始(),
		}));

		/* ③ 出口（**E9 只回 L10** ✓ 裁 (b)④）：W09 → L10-camp ——
		 *   闸门＝「人在 E9 ∧ 本次机会**未**用」✓；过门时：**用机会 ＋ 完成**（两件同笔 ✓）。
		 *   ⚠ 提前回城**不走这条边**（那是另一条路，且 ✗ 不算完成 ✓ —— 由 `完成()` 自己守 `当前===E9` ✓）。 */
		地图.addExit(new R.Exit({
			from: 'W09', to: B.聚落,
			text: '确认回城 · 用掉本次传送机会（E9）',
			when: () => 七.读().当前 === 'E9' && !七.读().机会.用,
			action: () => {
				/* ★片 3a：返程**事务**（结算 ＋ 用机会 ＋ 完成 ＋ 落幂等标记 —— **同一笔** ✓）。
				 *   ★裁文纠正①「一处函数＋顺序调用 ≠ 可靠提交」⇒ 三件全在事务内 ⇒ 任意失败 ⇒ **一起回滚** ✓；
				 *   ★裁文纠正②「提交拒绝必须**真挡住移动**」：本 pin 的 `MapScene` 判 `exit.action() !== false`
				 *   （`src/core/60-map.js:377` ✓）⇒ 此处**必须返回 `false`** ✓（返回 `{ok:false}` ✗ 不挡 ✓）。 */
				const r = B.返程结算?.返程事务?.({ 实例: 七.读().机会.实例,
					演出: (栏) => R.note?.(B.返程结算.演出(栏)) });
				if (!r) return true;                       // （✗ 无结算模块时不动旧行为 ✓）
				if (!r.ok) { R.note?.(`✗ ${r.why}`); return false; }
				return true;
			},
		}));

		/* ③b ★**教程内合法提前返程**（S6 `books#400` 裁 B ✓）：与 ③ 的 E9 出口**同一事务 ＋
		 *   同一幂等键空间** ✓（`request = sevenNames:返程:${实例}` ✓），只差**是否完成**：
		 *   ★提前 ⇒ **✗ 不完成** ✓（设计 §6「提前回城不算完成」✓）；E0 入场**不消费**机会 ✓（② ✓）。
		 *   闸门用**地点**（✗ 非 E9 的任意 W09 节点 ✓）＋ 机会未用 ✓ —— ⚠ E9 处**不显示**本边
		 *   （E9 有自己的「确认回城」= 完成路 ✓），两面**互斥**、✗ 不重复入口 ✓。 */
		地图.addExit(new R.Exit({
			from: 'W09', to: B.聚落,
			text: '提前结束本次出城 · 用掉本次传送机会（✗ 不算完成）',
			when: () => 七.读().已开始 && 七.读().态 !== '完成' && 七.读().当前 !== 'E9' && !七.读().机会.用,
			action: () => {
				const r = B.返程结算?.返程事务?.({ 实例: 七.读().机会.实例, 完成: false,
					演出: (栏) => R.note?.(B.返程结算.演出(栏)) });
				if (!r) return true;
				if (!r.ok) { R.note?.(`✗ ${r.why}`); return false; }   // ★拒 ⇒ 真挡移动（同 ③ ✓）
				return true;
			},
		}));

		/* ④ **互斥**：把既有 `L10-gate → L11` 的闸门**外包一层**「教程已完成」✓
		 *   ★只改**闸门函数**、✗ 不动 `from`/`to`/`text`/那条边的存在性 ✓（旧 L11 实体一字未动 ✓ 裁 (b)②）。 */
		const 旧门 = (地图.exits ?? []).find((e) => e.from === 'L10-gate' && e.to === 'L11');
		if (旧门) {
			const 旧闸 = 旧门.when;
			旧门.when = () => (typeof 旧闸 !== 'function' || 旧闸()) && !应分流();
		}
	}
}
