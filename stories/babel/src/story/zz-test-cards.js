/* 巴别之井 · **测试模式 · 卡面**（`books#413` A2 · 层 4）——「设账 ＋ 走真规则 ＋ 记结果」的**唯一调用面**
 *
 * ## 依据（A2 六项终裁，`#413` 评论 `6018185312`；1 项 ①「乙案：一张真战斗 ＋ 一张真奖励 ＋ 另列固定结束控制」）
 *   · ①**目录与池**：卡体取自 `zz-test-mode.js` 的 `卡目录`（恰两张 ✓）；**「指定事件」入口只认目录成员** ✓；
 *   · ①「复用正式规则、执行与结算；✗ 另造第二套战斗/奖励/掉落算法」⇒ 本档**只做调用与记账**：
 *     战斗走 `七名河战斗.战斗行动`（其取玩家/源/会话已按运行上下文 ✓），奖励走 `七名河.交付`
 *     （引擎**参数化**交付原语 ⇒ 落**测试背包** ✓）；
 *   · §二「**抽卡、抽奖和掷骰分别记账**」⇒ 本档给三本账：`抽卡`（选池/发卡）、`抽奖`（交付/掉落）、
 *     `掷骰`（**读该会话随机源自己的计数** ✓ —— ✗ 本档自数，那是第二套口径 ✓）；
 *   · §二「**纯查看/预览不得抽奖、建实例或结算**」⇒ `纯查看(场次id)` 只读，**✗ 任何抽取** ✓（判据断计数不变 ✓）。
 *
 * ## 形
 *   `setup.BABEL.测试卡 = { 备场, 跑战斗卡, 跑奖励卡, 纯查看, 账目, 入场 }`
 *   · `备场(场次id)` ⇒ 给该场次一份**合法七名河域**（进行中·当前＝入口）＋ 目录给装；✗ 掷任何骰 ✓
 *   · `跑战斗卡(场次id, {interactive})` ⇒ 走**真**固定敌组战斗；结果写回**该会话的域** ✓
 *   · `跑奖励卡(场次id)` ⇒ 走**唯一交付口**（落测试背包 ✓）；结果写回该会话的域 ✓
 *   · `入场()` ⇒ 开始菜单的入口动作：开测试局 ＋ 跑一张卡 ＋ 报读数（✗ 动正式局一个字节 ✓）
 */
(function () {
	'use strict';

	setup.BABEL = setup.BABEL ?? {};

	const 模式 = () => setup.BABEL.测试模式;
	const 内容 = () => setup.BABEL_CONTENT?.七名河内容 ?? {};
	const 战斗 = () => setup.BABEL.七名河战斗;
	const 规则 = () => setup.BABEL.七名河;
	/** 运行上下文门（层 2/3 的接缝都在它上面 ✓）。 */
	const 运 = () => setup.BABEL.运行;

	/** 本场次的账（★「分别记账」：抽卡／抽奖 由本档累加；**掷骰读源自己的计数** ✓）。
	 *   ★账存在**该会话的域**里（`事实.账目`）⇒ 属「合法测试事实」⇒ 跨刷新可恢复 ✓（✗ 只挂句柄上）。 */
	const 域账 = (句) => (域(句)?.账目 ?? { 抽卡: 0, 抽奖: 0 });
	/** 记一笔（只动**该会话**的域 ✓）。 */
	const 记 = (句, 类, n = 1) => {
		const a = 域账(句);
		const v = (a[类] ?? 0) + n;
		写域(句, { 账目: { ...a, [类]: v } });
		return v;
	};

	/** 域：该会话的**活体事实**（同 `00-seven-names.js` 的取法 —— 状态机是就地改 ✓）。 */
	const 域 = (句) => (句?.会话?._facts?.事实 ?? null);
	/** 写域：并补丁（会话自己的账 ✓）。 */
	const 写域 = (句, 补) => 句.会话.commit({ 事实: { ...(域(句) ?? {}), ...补 } });

	/** 备场：合法七名河域 ＋ 目录给装（✗ 掷骰、✗ 结算 —— 纯布置 ✓）。 */
	const 备场 = (场次id) => {
		const 句 = 模式()?.取?.(场次id);
		if (!句) return { ok: false, code: 'TEST_MODE_NO_SESSION_HANDLE' };
		const C = 内容();
		const 卡 = 句.卡;
		写域(句, {
			/* ★「当前」＝**该卡点名的节点**（战斗卡 ⇒ `E3` ✓）—— ✗ 停在不含该卡语义的入口，
			 *   那样 `战斗行动` 会以 `SEVEN_NOT_BATTLE` 直接退出（本席首版就栽在这里 ✗）。 */
			态: '进行中', 当前: 卡.节点 ?? C.入口 ?? 'E0', 结果: {}, 机会: { 用: false, 实例: `测试-${句.场次id}` }, 路径: [],
			卡: 卡.卡id, 类: 卡.类,
		});
		/* 给装：件快照须**完整**（缺 `charges` ⇒ `reviveItem` 报「快照为空」✗ —— `#413` 层 2 的踩坑 ✓）。 */
		if (卡.类 === '战斗') {
			setup.RPG.deposit(句.玩家.items, 'club', 1);
			setup.RPG.deposit(句.玩家.items, 'bandage', 2);
		}
		return { ok: true, 场次id: 句.场次id, 卡: 卡.卡id, 域: 域(句), 账: 域账(句) };
	};

	/** 跑战斗卡：走**真**规则（`战斗行动` 的玩家/源/会话皆按运行上下文 ✓）。 */
	const 跑战斗卡 = async (场次id, { interactive = false } = {}) => {
		const 句 = 模式()?.取?.(场次id);
		if (!句) return { ok: false, code: 'TEST_MODE_NO_SESSION_HANDLE' };
		if (句.卡.类 !== '战斗') return { ok: false, code: 'TEST_CARD_WRONG_KIND', why: `本卡是「${句.卡.类}」` };
		/* 「抽卡」＝发下这张卡（选池/指定事件 ⇒ 台账上记一笔 ✓；✗ 与「掷骰」混一账 ✓） */
		记(句, '抽卡');
		const 掷骰前 = 句.rng.计数 ?? 0;
		const 果 = await 运().在(句.上下文, () => 战斗().战斗行动(0, { interactive }));
		写域(句, { 结果: { ...(域(句)?.结果 ?? {}), [内容().入口 ?? 'E0']: { 战果: 果?.战果 ?? null, 成败: 果?.成败 ?? null } } });
		return {
			ok: true, 场次id: 句.场次id, 卡: 句.卡.卡id, 果,
			掷骰: (句.rng.计数 ?? 0) - 掷骰前,                     // ★「掷骰」账＝**该源自己的计数**差 ✓
			账: 域账(句),
		};
	};

	/** 跑奖励卡：走**唯一交付口**（`七名河.交付` ⇒ 测试背包 ✓）。 */
	const 跑奖励卡 = (场次id) => {
		const 句 = 模式()?.取?.(场次id);
		if (!句) return { ok: false, code: 'TEST_MODE_NO_SESSION_HANDLE' };
		if (句.卡.类 !== '奖励') return { ok: false, code: 'TEST_CARD_WRONG_KIND', why: `本卡是「${句.卡.类}」` };
		记(句, '抽卡');
		const loot = 句.卡.交付 ?? {};
		const 前 = 句.玩家.items.length;
		const 件 = 运().在(句.上下文, () => 规则().交付(loot));
		if (件?.length) 记(句, '抽奖');                          // ★「抽奖」＝真交付（✗ 与「抽卡」混 ✓）
		写域(句, { 态: '完成', 结果: { ...(域(句)?.结果 ?? {}), 奖励: 件.map(([id, n]) => ({ id, n })) } });
		return { ok: true, 场次id: 句.场次id, 卡: 句.卡.卡id, 交付: 件, 背包增: 句.玩家.items.length - 前, 账: 域账(句) };
	};

	/** 纯查看：**只读**（✗ 抽卡功能、✗ 建实例、✗ 结算 —— 判据断「计数分毫不变」✓）。 */
	const 纯查看 = (场次id) => {
		const 句 = 模式()?.取?.(场次id);
		if (!句) return { ok: false, code: 'TEST_MODE_NO_SESSION_HANDLE' };
		const d = 域(句) ?? {};
		return {
			ok: true, 场次id: 句.场次id, 卡: 句.卡.卡id, 类: 句.卡.类, 态: d.态 ?? null,
			背包件数: 句.玩家.items.length, 账: 域账(句), 掷骰累计: 句.rng.计数 ?? 0,
		};
	};

	/** 账目：三类**分开**给出（抽卡／抽奖 本档累加；掷骰 ＝ 该源自己的计数 ✓）。 */
	const 账目 = (场次id) => {
		const 句 = 模式()?.取?.(场次id);
		if (!句) return { ok: false, code: 'TEST_MODE_NO_SESSION_HANDLE' };
		const a = 域账(句);
		return { ok: true, 场次id: 句.场次id, 抽卡: a.抽卡 ?? 0, 抽奖: a.抽奖 ?? 0, 掷骰: 句.rng.计数 ?? 0 };
	};

	/** **开始菜单入口**：开测试局 ⇒ 跑「战斗卡」⇒ 报读数（✗ 动正式局一个字节 ✓；✗ 授胜/补奖/复活 ✓）。 */
	const 入场 = async () => {
		const M = 模式();
		if (!M) return { ok: false, code: 'TEST_MODE_ABSENT', why: '测试模式未装载' };
		let 开 = null;
		try { 开 = M.开('test-card-battle'); }
		catch (e) { setup.RPG?.perform?.(`开发测试模式暂不可用：${e?.message ?? e}`); return { ok: false, code: e?.code ?? 'TEST_MODE_OPEN_FAILED', why: e?.message }; }
		备场(开.场次id);
		const 果 = await 跑战斗卡(开.场次id, { interactive: false });
		const 账 = 账目(开.场次id);
		setup.RPG?.perform?.(
			`【测试局】卡：${开.卡.显示名}｜战果：${果?.果?.战果 ?? '—'}｜`
			+ `抽卡 ${账.抽卡} · 抽奖 ${账.抽奖} · 掷骰 ${账.掷骰}（✗ 写正式档）`);
		return { ok: true, 场次id: 开.场次id, 卡: 开.卡.卡id, 果: 果?.果 ?? null, 账,
			继续: () => 模式().结束(开.场次id) };
	};

	setup.BABEL.测试卡 = Object.freeze({ 备场, 跑战斗卡, 跑奖励卡, 纯查看, 账目, 入场 });
})();
