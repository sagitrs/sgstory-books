/* 巴别之井 · **运行上下文**（`books#413` A2 · S2）—— 把「正式规则的读者」从全局单例解耦到**按上下文取**
 *
 * ## 依据（A2 裁 5 ＋ S1 甲案 §三）
 *   · ✗ **借正式玩家／随机流／状态／全局订阅**后再回滚（明文禁）⇒ 故本档**不换装全局**，只提供**上下文选择**；
 *   · ✗ **另造一套战斗/奖励数学**（裁 §二 禁）⇒ 两卡与正式局**共用同一条规则代码**，只是**取对象的口**不同；
 *   · 「五个故事热点**不是**完整隔离证明」⇒ 本档只解**对象／账**这一层，rng 面由引擎接缝（甲案）另行绑定 ✓；
 *   · 「不预批『当前运行()』的具体 API 或事实 owner」⇒ 本档的形与字段名**属提案**，候评审 ✓。
 *
 * ## 形（提案）
 *   `setup.BABEL.运行 = { 正式(), 取(), 置(c), 还原(), 在(c, fn), 栈深() }`
 *   上下文 ＝ `{ 名, 玩家(), 账(), rng() }`（皆为**取用函数** ⇒ 每次现读，✗ 装载期抓引用）
 *   · **正式上下文**＝现档的全局源：`setup.DND3.Player`／`State.variables.babelRun`（经 `BS.本局账` 的**唯一口径** ✓
 *     —— ✗ 本档另写一份默认账形，那会变成「同一个量两套算法」）／`RPG.rng`；
 *   · **测试上下文**＝测试会话自有对象（由 `zz-test-mode.js` 建）⇒ 与正式上下文**并列**，✗ 借用正式对象。
 *
 * ## 纪律
 *   · `在(c, fn)` 用 `try/finally` ⇒ **异常也还原** ✓（✗ 让测试上下文留在场上）；
 *   · ✗ 本档不建会话、✗ 不写存档、✗ 不碰 rng（那是引擎接缝与本档调用方的事）✓。
 */
(function () {
	'use strict';

	setup.BABEL = setup.BABEL ?? {};

	/** 正式上下文：**取用函数**形（每次现读 ⇒ 玩家对象被换掉时不会失效 ✓）。 */
	const 正式 = () => ({
		名: '正式',
		玩家: () => setup.DND3?.Player ?? null,
		/* ★唯一口径：本局账的**读写**都走 `world/encounters.js` 既有的 `run()`（本档 ✗ 再写一份默认账形）。 */
		账: () => setup.BABEL.本局账?.() ?? null,
		rng: () => RPG.rng,
		场次id: null,   // ★正式局没有会话身份（✗ 拿它当测试标识）—— 测试上下文自带 ✓
	});

	/** 当前上下文**栈**（缺省＝正式）。栈式 ⇒ 置/还原严格配对 ✓（供嵌套场景）。 */
	const 栈 = [];
	/** 取当前上下文（✗ 传参者 ⇒ 取栈顶；空栈 ⇒ 正式 ✓）。 */
	const 取 = () => (栈.length ? 栈[栈.length - 1] : 正式());
	/** 置上下文（返回它，便于 `const c = 置(x)` 形）。 */
	const 置 = (c) => { 栈.push(c); return c; };
	/** 还原上一上下文（返回被弹出者；空栈 ⇒ `null`）。 */
	const 还原 = () => (栈.length ? 栈.pop() : null);
	/** 以某上下文跑一段：**异常也保证还原** ✓。 */
	const 在 = (c, fn) => { 置(c); try { return fn(); } finally { 还原(); } };

	setup.BABEL.运行 = { 正式, 取, 置, 还原, 在, 栈深: () => 栈.length };
})();
